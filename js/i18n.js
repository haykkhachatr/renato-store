  var lang = 'hy';
  var LOCALE = { hy: 'hy-AM', en: 'en-GB', ru: 'ru-RU' };

  function t(key, vars) {
    var s = dict[lang][key];
    if (s == null) s = dict.en[key];
    if (s == null) return key;
    if (vars) s = s.replace(/\{(\w+)\}/g, function (m, k) { return vars[k] != null ? vars[k] : m; });
    return s;
  }
  function has(key) { return dict.en[key] != null; }
  function setLang(l) {
    if (LANGS.indexOf(l) < 0) l = 'hy';
    lang = l;
    document.documentElement.lang = l;
    try { localStorage.setItem('renato.lang', l); } catch (e) {}
  }
  function getLang() { return lang; }
  function detect() {
    var saved = null;
    try { saved = localStorage.getItem('renato.lang'); } catch (e) {}
    if (saved && LANGS.indexOf(saved) >= 0) return saved;
    return (window.RENATO && window.RENATO.defaultLang) || 'hy';
  }
  /* number → "18 900 ֏" */
  function money(n) {
    var s = String(Math.round(n)).replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
    return s + ' ' + (window.RENATO ? window.RENATO.currency : '֏');
  }
  /* "text with *emphasis*" -> html */
  function emph(s) {
    return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/\*([^*]+)\*/g, '<em>$1</em>');
  }
  function pick(obj) { return obj ? (obj[lang] || obj.en || '') : ''; }

